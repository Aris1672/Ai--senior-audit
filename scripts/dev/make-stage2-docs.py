def pdf(name,pages):
    c=canvas.Canvas(out+'/'+name,pagesize=A4); w,h=A4
    for title,lines in pages:
        y=h-16*mm; c.setFont('DV',7.5); c.setFillGray(0.45); c.drawString(15*mm,y,MARK); c.setFillGray(0); y-=12*mm
        c.setFont('DVB',13); c.drawString(15*mm,y,title); y-=9*mm; c.setFont('DV',9.5)
        for l in lines:
            for part in (textwrap.wrap(l,98) or ['']):
                c.drawString(15*mm,y,part); y-=5.2*mm
            y-=1.2*mm
        c.showPage()
    c.save()
